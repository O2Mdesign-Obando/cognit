import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const root = process.cwd();
const demoRoot = path.join(root, "dist/learninghub/demo");
const outputPath = path.join(root, "src/demo/cognit-localization-route-manifest.js");

async function collectIndexFiles(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const nested = await Promise.all(entries.map(async (entry) => {
    const target = path.join(directory, entry.name);
    if (entry.isDirectory()) return collectIndexFiles(target);
    return entry.isFile() && entry.name === "index.html" ? [target] : [];
  }));
  return nested.flat();
}

const routes = (await collectIndexFiles(demoRoot))
  .map((file) => {
    const relative = path.relative(path.join(root, "dist"), path.dirname(file));
    return `/${relative.split(path.sep).join("/")}`.replace(/\/$/, "");
  })
  .sort();

const familyFor = (route) => route === "/learninghub/demo" ? "entry" : route.split("/")[3];
const counts = routes.reduce((result, route) => {
  const family = familyFor(route);
  result[family] = (result[family] ?? 0) + 1;
  return result;
}, {});
const fingerprint = createHash("sha256").update(`${routes.join("\n")}\n`).digest("hex");
const expectedCounts = { entry: 1, center: 321, coach: 26, student: 12, family: 14, hq: 11 };
if (Object.entries(expectedCounts).some(([family, count]) => counts[family] !== count)
  || Object.keys(counts).length !== Object.keys(expectedCounts).length) {
  throw new Error(`Unexpected Cognit Demo route counts: ${JSON.stringify(counts)}`);
}
if (fingerprint !== "818ee5dd04351d544b4b73f214edc8fcfb8fccdcb3ebfdb36f3030b2a43533e4") {
  throw new Error(`Unexpected Cognit Demo route fingerprint: ${fingerprint}`);
}

const source = `// Generated by scripts/generate-cognit-localization-route-manifest.mjs.\n`
  + `// Exact concrete routes, not unique screen designs.\n`
  + `export const COGNIT_DEMO_LOCALIZATION_MANIFEST = Object.freeze(${JSON.stringify(routes, null, 2)});\n\n`
  + `export const COGNIT_DEMO_LOCALIZATION_MANIFEST_META = Object.freeze(${JSON.stringify({ counts, fingerprint, reviewStatus: "SPANISH_HUMAN_REVIEW_PENDING" }, null, 2)});\n`;

if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8");
  if (current !== source) throw new Error("Cognit localization route manifest is stale. Run npm run localization:manifest.");
  console.log(`PASS Cognit localization manifest routes=${routes.length} sha256=${fingerprint}`);
} else {
  await writeFile(outputPath, source);
  console.log(`WROTE Cognit localization manifest routes=${routes.length} sha256=${fingerprint}`);
}
